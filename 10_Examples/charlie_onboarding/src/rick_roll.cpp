RickRoll::RickRoll()
: normal_(artwork), mirrored_(mirror(normal_))
{
}

const std::string & RickRoll::next()
{
  const std::string & result = flipped_ ? mirrored_ : normal_;
  flipped_ = !flipped_;
  return result;
}
