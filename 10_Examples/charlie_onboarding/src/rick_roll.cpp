std::string mirror(const std::string & image)
{
  std::istringstream input(image);
  std::string line;
  std::string result;
  while (std::getline(input, line)) {
    // The embedded image consists exclusively of three-byte UTF-8 Braille glyphs.
    for (std::size_t i = line.size(); i > 0; i -= 3) {
      const auto second = static_cast<unsigned char>(line[i - 2]);
      const auto third = static_cast<unsigned char>(line[i - 1]);
      const uint8_t dots = static_cast<uint8_t>(((second & 0x3f) << 6) | (third & 0x3f));
      const uint8_t flipped = static_cast<uint8_t>(
        ((dots & 0x07) << 3) | ((dots & 0x38) >> 3) |
        ((dots & 0x40) << 1) | ((dots & 0x80) >> 1));
      result += static_cast<char>(0xe2);
      result += static_cast<char>(0xa0 | (flipped >> 6));
      result += static_cast<char>(0x80 | (flipped & 0x3f));
    }
    if (!input.eof()) {
      result += '\n';
    }
  }
  return result;
}
